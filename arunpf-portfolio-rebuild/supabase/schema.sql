-- Run this in Supabase Dashboard -> SQL Editor.
-- Replace admin@arunpf.com with the exact email used for your Supabase admin account.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 254),
  project_type text,
  message text not null check (char_length(message) between 10 and 5000),
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;

drop policy if exists "Authenticated users can read contact messages" on public.contact_messages;
drop policy if exists "Only portfolio admin can read contact messages" on public.contact_messages;

create policy "Only portfolio admin can read contact messages"
  on public.contact_messages
  for select
  to authenticated
  using ((auth.jwt() ->> 'email') = 'admin@arunpf.com');

-- There is deliberately no public insert/update/delete policy.
-- The Edge Function writes using the server-side service-role key.
